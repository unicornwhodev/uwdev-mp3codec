"""Generate normative MPEG-1 Huffman codewords from pinned CC0 numerical data.

Only integer lookup-table initializers are parsed. No decoder code is emitted.
Usage: python3 scripts/generate_huffman_tables.py /path/to/minimp3.h
See docs/MPEG_SOURCES.md for provenance and the immutable input checksum.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import re

EXPECTED_SHA256 = '57e437c5c1f0e8b243885d3929c8973b5e6c778451e0100ab4251d19915cb3ad'
DIMENSIONS = [1,2,3,3,0,4,4,6,6,6,8,8,8,16,0,16,16,16,16,16,16,16,16,16,16,16,16,16,16,16,16,16]

def extract(source: str, name: str) -> list[int]:
    match = re.search(r'\b' + re.escape(name) + r'\s*\[[^;=]*=\s*\{([^}]+)\}', source)
    if not match:
        raise ValueError('missing numeric table ' + name)
    return [int(x) for x in re.findall(r'-?\d+', match.group(1))]

def decode_numeric_tree(table: list[int], base: int, dimension: int) -> list[tuple[int,int]]:
    out: dict[tuple[int,int], tuple[int,int]] = {}
    def visit(offset: int, width: int, prefix: int, prefix_len: int) -> None:
        for index in range(1 << width):
            value = table[base + offset + index]
            if value < 0:
                visit(-(value >> 3), value & 7, (prefix << width) | index, prefix_len + width)
            else:
                length = value >> 8
                if length > width:
                    raise ValueError('invalid numeric leaf')
                code = (prefix << length) | (index >> (width-length))
                symbol = (value & 15, (value >> 4) & 15)
                result = (code, prefix_len + length)
                if symbol in out and out[symbol] != result:
                    raise ValueError('non-unique normative codeword')
                out[symbol] = result
    visit(0, 5, 0, 0)
    if len(out) != dimension * dimension:
        raise ValueError('incomplete codebook')
    return [out[x,y] for x in range(dimension) for y in range(dimension)]

def count1_codes(table: list[int]) -> list[tuple[int,int]]:
    out: dict[int,tuple[int,int]] = {}
    for prefix in range(64):
        value = table[prefix >> 2]
        if not value & 8:
            width = value & 3
            value = table[(value >> 3) + ((prefix & 3) >> (2-width))]
        length, symbol = value & 7, value >> 4
        result = (prefix >> (6-length), length)
        if symbol in out and out[symbol] != result:
            raise ValueError('non-unique quadruple codeword')
        out[symbol] = result
    if len(out) != 16:
        raise ValueError('incomplete quadruple table')
    return [out[x] for x in range(16)]

def validate_prefix(codes: list[tuple[int,int]]) -> None:
    for i,(code,length) in enumerate(codes):
        assert 0 <= code < (1 << length)
        for other, other_length in codes[i+1:]:
            if length <= other_length:
                assert code != (other >> (other_length-length))
            else:
                assert other != (code >> (length-other_length))

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'encoder-android/src/main/cpp/codec/huffman_tables.hpp')
    args = parser.parse_args()
    data = args.source.read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise SystemExit('Refusing unpinned source: SHA-256 mismatch')
    source = data.decode('utf-8')
    tabs, indexes, linbits = (extract(source, n) for n in ['tabs','tabindex','g_linbits'])
    generated = ['// SPDX-License-Identifier: MIT', '// MPEG codeword data derived from CC0-1.0 minimp3 numerical tables.', '// Generated by scripts/generate_huffman_tables.py; see docs/MPEG_SOURCES.md.', '#pragma once', '#include <array>', '#include <cstdint>', 'namespace uwdev::mp3codec::detail {', 'struct HuffCode { std::uint32_t code; std::uint8_t length; };']
    distinct: dict[int, int] = {}
    names: list[str] = []
    for table_number in range(32):
        if table_number in [4,14]:
            names.append('nullptr')
            continue
        index = indexes[table_number]
        if index not in distinct:
            distinct[index] = table_number
            codes = decode_numeric_tree(tabs, index, DIMENSIONS[table_number])
            if table_number:
                validate_prefix(codes)
            generated.append(f'inline constexpr std::array<HuffCode, {len(codes)}> kHuff{table_number} = {{{{')
            for k in range(0,len(codes),8):
                generated.append('    '+', '.join(f'{{{c}U, {n}}}' for c,n in codes[k:k+8])+',')
            generated.append('}};')
        names.append(f'kHuff{distinct[index]}.data()')
    generated += ['struct HuffTable { const HuffCode* codes; std::uint8_t dimension; std::uint8_t linbits; };','inline constexpr std::array<HuffTable, 32> kHuffmanTables = {{']
    for i in range(32):
        generated.append(f'    {{{names[i]}, {DIMENSIONS[i]}, {linbits[i]}}},')
    generated.append('}};')
    for n in [32,33]:
        codes = count1_codes(extract(source,f'tab{n}'))
        validate_prefix(codes)
        generated.append(f'inline constexpr std::array<HuffCode,16> kCount1_{n} = {{{{')
        generated.append('    '+', '.join(f'{{{c}U, {length}}}' for c,length in codes)+',')
        generated.append('}};')
    generated.append('} // namespace uwdev::mp3codec::detail')
    args.output.write_text('\n'.join(generated)+'\n', encoding='utf-8')
    print(f'Generated {args.output}: {len(distinct)} unique pair codebooks, 2 quadruple codebooks; all prefix checks passed.')

if __name__ == '__main__':
    main()
