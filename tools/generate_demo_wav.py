"""Generate the original, license-clean two-second stereo WAV bundled with the demo."""
from pathlib import Path
import argparse
import hashlib
import json
import math
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'sample-app/src/main/assets')
    output = parser.parse_args().output
    output.mkdir(parents=True, exist_ok=True)
    rate = 48_000
    frames = rate * 2
    data = bytearray()
    for frame in range(frames):
        envelope = min(1.0, frame/(rate*0.04), (frames-1-frame)/(rate*0.04))
        for frequency in (440, 660):
            data.extend(struct.pack('<h', round(math.sin(2*math.pi*frequency*frame/rate)*5000*envelope)))
    path = output/'demo.wav'
    with wave.open(str(path), 'wb') as wav:
        wav.setnchannels(2); wav.setsampwidth(2); wav.setframerate(rate); wav.writeframes(data)
    manifest = {'name':'Original stereo tone demonstration','author':'Unicorn Who Dev','license':'MIT',
        'source':'Generated by tools/generate_demo_wav.py; no external recording or sample',
        'format':'PCM16LE','sample_rate':rate,'channels':2,'frames':frames,'duration_seconds':2,
        'left_hz':440,'right_hz':660,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
        'purpose':'Integration demo, not a musical or perceptual quality reference'}
    (output/'demo.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print('Generated demo.wav and demo.json')

if __name__ == '__main__':
    main()
